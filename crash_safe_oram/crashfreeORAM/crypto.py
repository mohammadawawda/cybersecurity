import os
import struct

from Crypto.Cipher import AES



NONCE_LENGTH= 12
DUMMY_ADDR=-1
TAG_LEN = 16
KEY_LEN = 32 #using aes 256
def random_key():
    """
    return a random key generated by os.urandom
    """
    return os.urandom(KEY_LEN)

class BlockCipher:
    """
    the purpose of this class is to encrypt a block of data either real or dummy
    """
    def __init__(self,key, block_size):
        if key is None or len(key) != KEY_LEN:
            raise ValueError("key must be of length 32")
        self.key = key
        self.block_size = block_size


    def cipher_length(self):
        return NONCE_LENGTH + 8 + self.block_size + TAG_LEN

    def encrypt_block(self,address, data):
        if len(data) > self.block_size:
            raise ValueError(f"data is {len(data)} bytes, block size is {self.block_size}")
        plaintext = struct.pack("<q", address) + data + bytes(self. block_size - len(data))
        nonce = os.urandom(NONCE_LENGTH)
        cipher = AES.new(self.key, AES.MODE_GCM, nonce=nonce)
        ciphertext, tag = cipher.encrypt_and_digest(plaintext)
        return nonce + tag + ciphertext

    def decrypt_block(self, encrypted):
        if len(encrypted) != self.cipher_length():
            raise ValueError("bad ciphertext length")
        nonce = encrypted[:NONCE_LENGTH]
        tag = encrypted[NONCE_LENGTH:NONCE_LENGTH + TAG_LEN]
        ciphertext = encrypted[NONCE_LENGTH + TAG_LEN:]
        cipher = AES.new(self.key, AES.MODE_GCM, nonce=nonce)
        plaintext = cipher.decrypt_and_verify(ciphertext, tag)
        address = struct.unpack("<q", plaintext[:8])[0]
        return address, plaintext[8:]

    def dummy(self):
        return self.encrypt_block(DUMMY_ADDR, os.urandom(self.block_size))